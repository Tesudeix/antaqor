/* ─── Загварт өгөх бүтэн заавар ──────────────────────────────────────────
   Амьд жишээ + давталтын хамгаалалт + өнцөг + CTA-г нэг мөр болгож нийлүүлнэ. */
export function buildVoicePrompt(recent: VoicePost[]): string {
  /* Жишээнд зөвхөн БОДИТОЙ постыг оруулна: маш богино ("hi", "1 лайк —
     их баярлалаа") постууд хэв маяг заахгүй, харин загварыг нэг мөрийн
     хариу руу татдаг. 60 тэмдэгтийн шүүлтүүр яг тэр хогийг таслана. */
  const samples = recent
    .map((p) => (p.text || "").trim())
    .filter((t) => t.length >= 60)
    .slice(0, 12);

  const examples = samples.length
    ? `\n\nЭНЭ ХҮНИЙ ЖИНХЭНЭ ПОСТУУД (хэлбэрийг нь дуурай, СЭДВИЙГ нь БИШ):\n\n${samples
        .map((t, i) => `--- ${i + 1} ---\n${t}`)
        .join("\n\n")}`
    : "";

  /* Давталтын хамгаалалт. Эхний мөр нь постын "сэдэв"-ийг хамгийн сайн
     төлөөлдөг тул түүгээр л хангалттай — бүтэн текстийг дахин илгээвэл
     контекст хоёр дахин том болно. */
  const usedOpeners = recent
    .map((p) => (p.text || "").split("\n")[0].trim())
    .filter((t) => t.length > 20)
    .slice(0, 25);

  const avoid = usedOpeners.length
    ? `\n\nЭДГЭЭР САНААГ АЛЬ ХЭДИЙН БИЧСЭН. Дахин бүү бич, өөр өнцгөөс ор:\n${usedOpeners
        .map((t) => `- ${t}`)
        .join("\n")}`
    : "";

  return `${VOICE_SPEC}${examples}${avoid}`;
}

/* ─── ЮҮЛҮҮРИЙН ШИНЖИЛГЭЭ ────────────────────────────────────────────────
   "Пост сайхан бичигдсэн үү" биш, "пост АЖИЛЛАЖ байна уу" гэдгийг хэмжинэ. */

export interface TriggerLite {
  keywords: string[];
  matchMode: string;
  enabled: boolean;
}

/** Постын сүүлийн мөрөөс сэтгэгдэлд бичихийг хүссэн үгийг сугална.
 *  "AI сурах бол prompt гэж бичээрэй" → "prompt" */
export function extractCtaKeyword(text: string): string | null {
  const m = text.match(/["“”']?([\p{L}\p{N}_-]+)["“”']?\s*гэж\s+бич/iu);
  return m ? m[1].trim() : null;
}

/** Пост дуудлагатай юу — түлхүүр үгээр, эсвэл лайк дуудлагаар. */
export function hasCta(text: string): boolean {
  return /гэж\s+бич/iu.test(text) || /зүрх\s+дараарай|зүрх\s*❤|зүрх$/iu.test(text.trim());
}

/** Тухайн түлхүүр үгэнд амьд trigger байгаа эсэх — юүлүүр тасарсан эсэх. */
export function keywordHasTrigger(keyword: string, triggers: TriggerLite[]): boolean {
  const k = keyword.toLowerCase().trim();
  if (!k) return true; // лайк-CTA нь trigger шаардахгүй
  return triggers.some(
    (t) =>
      t.enabled &&
      t.keywords.some((kw) => {
        const n = kw.toLowerCase().trim();
        if (!n) return false;
        // Сэтгэгдэл нь ЯГ тэр үг байна гэж үзнэ (хүн "prompt" гэж л бичнэ).
        return t.matchMode === "exact" ? n === k : k.includes(n) || n.includes(k);
      })
  );
}

export interface VoiceAnalysis {
  postCount: number;
  days: number;
  perDay: number;
  withCta: number;
  ctaRate: number;
  avgChars: number;
  /** Хэрэглэсэн CTA түлхүүр үг бүр, хэдэн удаа, амьд trigger байгаа эсэх. */
  ctaKeywords: { keyword: string; count: number; covered: boolean }[];
  /** Trigger байхгүй түлхүүр үгс — ЭНЭ БОЛ АЛДАГДСАН МӨНГӨ. */
  leaks: { keyword: string; count: number }[];
  topOpeners: string[];
}

export function analyzeVoice(posts: VoicePost[], triggers: TriggerLite[]): VoiceAnalysis {
  const real = posts.filter((p) => (p.text || "").trim().length > 0);
  const times = real
    .map((p) => new Date(p.timestamp).getTime())
    .filter((n) => Number.isFinite(n))
    .sort((a, b) => a - b);
  const spanMs = times.length > 1 ? times[times.length - 1] - times[0] : 0;
  const days = Math.max(1, Math.round(spanMs / 86_400_000));

  const withCta = real.filter((p) => hasCta(p.text)).length;

  const counts = new Map<string, number>();
  for (const p of real) {
    const k = extractCtaKeyword(p.text);
    if (k) counts.set(k.toLowerCase(), (counts.get(k.toLowerCase()) || 0) + 1);
  }

  const ctaKeywords = Array.from(counts.entries())
    .map(([keyword, count]) => ({ keyword, count, covered: keywordHasTrigger(keyword, triggers) }))
    .sort((a, b) => b.count - a.count);

  return {
    postCount: real.length,
    days,
    perDay: Number((real.length / days).toFixed(1)),
    withCta,
    ctaRate: real.length ? Math.round((withCta / real.length) * 100) : 0,
    avgChars: real.length
      ? Math.round(real.reduce((s, p) => s + p.text.length, 0) / real.length)
      : 0,
    ctaKeywords,
    leaks: ctaKeywords.filter((k) => !k.covered).map(({ keyword, count }) => ({ keyword, count })),
    topOpeners: real.slice(0, 8).map((p) => p.text.split("\n")[0].slice(0, 90)),
  };
}

